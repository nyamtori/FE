/** 재료/레시피 이름에 등장하는 키워드로 그나마 어울리는 이모지를 골라준다(정확한 매칭은 아님). */
const FOOD_EMOJI_KEYWORDS: [RegExp, string][] = [
  [/당근/, '🥕'],
  [/오이|피클/, '🥒'],
  [/수박/, '🍉'],
  [/사과/, '🍎'],
  [/바나나/, '🍌'],
  [/포도/, '🍇'],
  [/레몬/, '🍋'],
  [/토마토/, '🍅'],
  [/양파/, '🧅'],
  [/마늘/, '🧄'],
  [/고구마/, '🍠'],
  [/감자/, '🥔'],
  [/옥수수/, '🌽'],
  [/브로콜리/, '🥦'],
  [/버섯/, '🍄'],
  [/양배추|배추|김치/, '🥬'],
  [/쌀|현미|밥/, '🍚'],
  [/빵/, '🍞'],
  [/치즈/, '🧀'],
  [/우유|요거트|유제품/, '🥛'],
  [/계란|달걀/, '🥚'],
  [/스팸|햄|소시지/, '🥫'],
  [/소고기|돼지고기|고기/, '🥩'],
  [/닭|치킨/, '🍗'],
  [/생선|고등어|연어|참치/, '🐟'],
  [/새우|해산물/, '🍤'],
  [/면|라면|파스타|국수/, '🍜'],
]

export function guessFoodEmoji(name: string, fallback: string): string {
  for (const [pattern, emoji] of FOOD_EMOJI_KEYWORDS) {
    if (pattern.test(name)) return emoji
  }
  return fallback
}
